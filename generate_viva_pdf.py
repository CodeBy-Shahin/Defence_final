def write_text_file() -> None:
    OUT_DIR.mkdir(exist_ok=True)
    lines = [TITLE, SUBTITLE, ""]
    for index, (question, answer) in enumerate(QA_ITEMS, start=1):
        lines.append(f"{index}. Question: {question}")
        lines.append(f"Answer: {answer}")
        lines.append("")
    TXT_PATH.write_text("\n".join(lines), encoding="utf-8")


def add_wrapped_text(
    page: fitz.Page,
    text: str,
    x: float,
    y: float,
    width: float,
    size: float,
    font: str,
    color: tuple[float, float, float],
) -> float:
    max_chars = max(35, int(width / (size * 0.47)))
    lines = textwrap.wrap(text, width=max_chars) or [""]
    line_height = size * 1.36
    for line in lines:
        page.insert_text((x, y), line, fontsize=size, fontname=font, color=color)
        y += line_height
    return y


def write_pdf() -> None:
    OUT_DIR.mkdir(exist_ok=True)
    doc = fitz.open()
    page_w, page_h = fitz.paper_size("a4")
    margin = 54
    content_w = page_w - margin * 2
    page = doc.new_page(width=page_w, height=page_h)
    y = margin

    def new_page() -> None:
        nonlocal page, y
        page = doc.new_page(width=page_w, height=page_h)
        y = margin

    def ensure(space: float) -> None:
        if y + space > page_h - margin:
            new_page()

    def add(
        text: str,
        size: float = 10.5,
        bold: bool = False,
        before: float = 0,
        after: float = 6,
        indent: float = 0,
        color: tuple[float, float, float] = (0.08, 0.1, 0.14),
    ) -> None:
        nonlocal y
        y += before
        font = "Helvetica-Bold" if bold else "Helvetica"
        wrap_width = max(35, int((content_w - indent) / (size * 0.47)))
        line_count = max(1, len(textwrap.wrap(text, width=wrap_width)))
        ensure(line_count * size * 1.36 + after + 4)
        y = add_wrapped_text(page, text, margin + indent, y, content_w - indent, size, font, color)
        y += after

    add(TITLE, 18, True, after=10, color=(0.06, 0.12, 0.24))
    add(SUBTITLE, 10.5, False, after=18, color=(0.32, 0.36, 0.42))
    add("Use this document for viva, supervisor questions, and project defense preparation.", 10.5, False, after=14, color=(0.2, 0.31, 0.55))

    for index, (question, answer) in enumerate(QA_ITEMS, start=1):
        add(f"{index}. Question: {question}", 11.1, True, before=5, after=4)
        add(f"Answer: {answer}", 10.4, False, after=7, indent=14)

    for index, p in enumerate(doc, start=1):
        p.insert_text((page_w / 2 - 8, page_h - 24), str(index), fontsize=9, fontname="Helvetica", color=(0.45, 0.45, 0.45))

    doc.save(PDF_PATH)
    doc.close()


def main() -> None:
    write_text_file()
    write_pdf()
    print(PDF_PATH)
    print(TXT_PATH)


if __name__ == "__main__":
    main()
